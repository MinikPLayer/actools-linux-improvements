#!/usr/bin/env python3
"""
Generates FirstFloor.ModernUI/Compat/WpfEvents.g.cs: Add<Event>/Remove<Event> extension methods which emulate WPF’s events
on Avalonia controls (C# can’t have extension events). cs_rules.py rewrites `x.MouseDown += h;` to `x.AddMouseDown(h);`.
"""
EVENTS = []   # (name, argsType, routedEvent, routing, filter)
PTR = 'PointerEventArgs'
def ptr(prefix, tunnel):
    routing = 'RoutingStrategies.Tunnel' if tunnel else 'RoutingStrategies.Bubble'
    for kind, ev, upd in (('Down', 'PointerPressedEvent', 'pressed'), ('Up', 'PointerReleasedEvent', 'released')):
        EVENTS.append((prefix + 'Mouse' + kind, PTR, 'InputElement.' + ev, routing, None))
        for b in ('Left', 'Right', 'Middle'):
            EVENTS.append((prefix + 'Mouse' + b + 'Button' + kind, PTR, 'InputElement.' + ev, routing, b))
    EVENTS.append((prefix + 'MouseMove', PTR, 'InputElement.PointerMovedEvent', routing, None))
    EVENTS.append((prefix + 'MouseWheel', 'PointerWheelEventArgs', 'InputElement.PointerWheelChangedEvent', routing, None))
    EVENTS.append((prefix + 'KeyDown', 'KeyEventArgs', 'InputElement.KeyDownEvent', routing, None))
    EVENTS.append((prefix + 'KeyUp', 'KeyEventArgs', 'InputElement.KeyUpEvent', routing, None))
    EVENTS.append((prefix + 'TextInput', 'TextInputEventArgs', 'InputElement.TextInputEvent', routing, None))
ptr('', False)
ptr('Preview', True)
EVENTS = [e for e in EVENTS if e[0] not in ('KeyDown', 'KeyUp', 'TextInput')]  # exist in Avalonia as real events
EVENTS += [
    ('MouseEnter', PTR, 'InputElement.PointerEnteredEvent', 'RoutingStrategies.Direct', None),
    ('MouseLeave', PTR, 'InputElement.PointerExitedEvent', 'RoutingStrategies.Direct', None),
    ('LostMouseCapture', 'PointerCaptureLostEventArgs', 'InputElement.PointerCaptureLostEvent', 'RoutingStrategies.Direct', None),
    ('GotKeyboardFocus', 'GotFocusEventArgs', 'InputElement.GotFocusEvent', 'RoutingStrategies.Bubble', None),
    ('LostKeyboardFocus', 'RoutedEventArgs', 'InputElement.LostFocusEvent', 'RoutingStrategies.Bubble', None),
    ('ContextMenuOpening', 'ContextRequestedEventArgs', 'Control.ContextRequestedEvent', 'RoutingStrategies.Bubble', None),
    ('Drop', 'DragEventArgs', 'DragDrop.DropEvent', 'RoutingStrategies.Bubble', None),
    ('DragOver', 'DragEventArgs', 'DragDrop.DragOverEvent', 'RoutingStrategies.Bubble', None),
    ('DragEnter', 'DragEventArgs', 'DragDrop.DragEnterEvent', 'RoutingStrategies.Bubble', None),
    ('DragLeave', 'DragEventArgs', 'DragDrop.DragLeaveEvent', 'RoutingStrategies.Bubble', None),
    ('PreviewDrop', 'DragEventArgs', 'DragDrop.DropEvent', 'RoutingStrategies.Tunnel', None),
    ('PreviewDragOver', 'DragEventArgs', 'DragDrop.DragOverEvent', 'RoutingStrategies.Tunnel', None),
]
# PreviewKeyDown & co were removed above only for the non-preview names; keep preview ones
out = ['// <auto-generated> by PortTools/gen_wpf_events.py </auto-generated>',
       'using System;', 'using System.Collections.Generic;', 'using System.Runtime.CompilerServices;',
       'using Avalonia.Controls;', 'using Avalonia.Input;', 'using Avalonia.Interactivity;', '',
       'namespace System.Windows {',
       '    public static class WpfEvents {',
       '        private static readonly ConditionalWeakTable<object, Dictionary<(string, Delegate), Delegate>> Wrappers =',
       '                new ConditionalWeakTable<object, Dictionary<(string, Delegate), Delegate>>();',
       '',
       '        private static Dictionary<(string, Delegate), Delegate> Get(object o) => Wrappers.GetValue(o, _ => new Dictionary<(string, Delegate), Delegate>());',
       '']
for name, args, ev, routing, flt in EVENTS:
    cond = ''
    if flt:
        cond = f'if (!e.GetCurrentPoint(null).Properties.PointerUpdateKind.ToString().StartsWith("{flt}")) return; '
        # for released events PointerUpdateKind is e.g. LeftButtonReleased
    wrapper_type = {'InputElement.PointerPressedEvent': 'PointerPressedEventArgs', 'InputElement.PointerReleasedEvent': 'PointerReleasedEventArgs'}.get(ev, args)
    out.append(f'''        public static void Add{name}(this Interactive target, EventHandler<{args}> handler) {{
            EventHandler<{wrapper_type}> wrapper = (s, e) => {{ {cond}handler(s, e); }};
            Get(target)[("{name}", handler)] = wrapper;
            target.AddHandler({ev}, wrapper, {routing}, false);
        }}

        public static void Remove{name}(this Interactive target, EventHandler<{args}> handler) {{
            if (Get(target).Remove(("{name}", handler), out var w)) target.RemoveHandler({ev}, (EventHandler<{wrapper_type}>)w);
        }}
''')
out += ['    }', '}']
open('/project/FirstFloor.ModernUI/Compat/WpfEvents.g.cs', 'w').write('\n'.join(out) + '\n')
names = [e[0] for e in EVENTS]
open('/project/PortTools/wpf_event_names.txt', 'w').write('\n'.join(names) + '\n')
print(len(names), 'events')
